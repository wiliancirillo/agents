#!/usr/bin/env bash
# Creates the global per-tool symlinks pointing at the canonical AGENTS.md.
# Idempotent: updates existing symlinks, never overwrites regular files.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CANON="$ROOT/AGENTS.md"

link() {
  local linkpath="$1"
  mkdir -p "$(dirname "$linkpath")"
  if [ -L "$linkpath" ]; then
    ln -sfn "$CANON" "$linkpath"
    echo "updated: $linkpath -> $CANON"
  elif [ -e "$linkpath" ]; then
    echo "SKIP (regular file exists, resolve manually): $linkpath"
  else
    ln -s "$CANON" "$linkpath"
    echo "linked:  $linkpath -> $CANON"
  fi
}

link "$HOME/.claude/CLAUDE.md"
link "$HOME/.codex/AGENTS.md"

# Gemini CLI reads GEMINI.md; only wire it if the tool is present.
if [ -d "$HOME/.gemini" ]; then
  link "$HOME/.gemini/GEMINI.md"
fi

# Hermes loads AGENTS.md only from the cwd and ignores other tools' global
# files. Deliver the rules as a generated skill listed in skills.auto_load,
# which injects it into every new session. The skill is a copy, not a link:
# re-run this script after editing AGENTS.md or RTK.md.
HERMES_DIR="${HERMES_HOME:-$HOME/.hermes}"
if [ -d "$HERMES_DIR" ]; then
  SKILL_NAME="agents-rules"
  SKILL="$HERMES_DIR/skills/personal/$SKILL_NAME/SKILL.md"
  MARKER="generated by $ROOT/wire.sh"
  HASH="$(cat "$CANON" "$ROOT/RTK.md" | sha256sum | cut -d' ' -f1)"

  if [ -e "$SKILL" ] && ! grep -qF "$MARKER" "$SKILL"; then
    echo "SKIP (not generated by wire.sh, resolve manually): $SKILL"
  elif [ -e "$SKILL" ] && grep -qF "source-sha256: $HASH" "$SKILL"; then
    echo "ok (up to date): $SKILL"
  else
    mkdir -p "$(dirname "$SKILL")"
    {
      printf -- '---\nname: %s\ndescription: Personal operating rules from %s, loaded in every session.\n---\n\n' "$SKILL_NAME" "$CANON"
      printf '<!-- %s; source-sha256: %s. Edit the source and re-run wire.sh, never this file. -->\n\n' "$MARKER" "$HASH"
      # @RTK.md is Claude Code include syntax; inline the file instead.
      grep -vx '@RTK.md' "$CANON"
      printf '\n'
      cat "$ROOT/RTK.md"
    } >"$SKILL.tmp"
    mv "$SKILL.tmp" "$SKILL"
    echo "generated: $SKILL"
  fi

  if ! command -v hermes >/dev/null 2>&1; then
    echo "SKIP (hermes not on PATH): add $SKILL_NAME to skills.auto_load manually"
  else
    raw="$(hermes config get skills.auto_load 2>/dev/null)"
    current="$(printf '%s\n' "$raw" | sed -n 's/^[[:space:]]*-[[:space:]]*//p')"
    if [ -z "$current" ] && printf '%s' "$raw" | grep -q '[[:alnum:]]' && ! printf '%s' "$raw" | grep -qxE '[[:space:]]*(\[\]|None|null)[[:space:]]*'; then
      echo "SKIP (unrecognised skills.auto_load output, add $SKILL_NAME manually): $raw"
    elif printf '%s\n' "$current" | grep -qx "$SKILL_NAME"; then
      echo "ok (auto_load has $SKILL_NAME)"
    else
      list="$(printf '%s\n' "$current" "$SKILL_NAME" | sed '/^$/d' | sed 's/.*/"&"/' | paste -sd, -)"
      hermes config set skills.auto_load "[$list]" >/dev/null
      echo "auto_load: [$list]"
    fi
  fi

  # Older versions of this script appended a pointer to SOUL.md. The skill
  # supersedes it; SOUL.md is a regular file, so only report it.
  if [ -f "$HERMES_DIR/SOUL.md" ] && grep -qF "$CANON" "$HERMES_DIR/SOUL.md"; then
    echo "NOTE (obsolete pointer, remove manually): $HERMES_DIR/SOUL.md"
  fi
fi

echo "done."
